            ELSE NULL::integer
        END AS first_receipt_lead_days,
        CASE
            WHEN ph.sent_at IS NOT NULL AND r.last_receipt_date IS NOT NULL AND COALESCE(r.accepted_qty, 0::numeric) >= GREATEST(pl.ordered_qty - COALESCE(pl.cancelled_qty, 0::numeric), 0::numeric) THEN r.last_receipt_date - ph.sent_at::date
