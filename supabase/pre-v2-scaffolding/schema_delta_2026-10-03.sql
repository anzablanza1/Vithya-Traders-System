    GREATEST(p.updated_at, COALESCE(po.updated_at, p.updated_at), COALESCE(pp.updated_at, p.updated_at)) AS updated_at
   FROM purchase_sku_analytics p
     LEFT JOIN po_sku_analytics po ON po.parent_sku = p.parent_sku
     LEFT JOIN purchase_sku_policy pp ON pp.parent_sku = p.parent_sku;
;
COMMENT ON VIEW public.v_purchase_to_inventory IS "Supplier-neutral, cost-free Purchase-to-Inventory supply feed.";

-- -----------------------------------------------------------------------------
-- VIEW: public.v_stock_parent_current
CREATE OR REPLACE VIEW public.v_stock_parent_current AS
 SELECT regexp_replace(TRIM(BOTH FROM item_code), '/+$'::text, ''::text) AS parent_sku,
    max(product_name) AS product_name,
    max(category) AS category,
    max(brand) AS brand,
    sum(COALESCE(qty_w, 0::numeric)) AS qty_w,
    sum(COALESCE(qty_wo, 0::numeric)) AS qty_wo,
    sum(COALESCE(qty_total, 0::numeric)) AS qty_total,
    max(loaded_at) AS loaded_at
   FROM stock_live
  WHERE NULLIF(TRIM(BOTH FROM item_code), ''::text) IS NOT NULL
  GROUP BY (regexp_replace(TRIM(BOTH FROM item_code), '/+$'::text, ''::text));
;
COMMENT ON VIEW public.v_stock_parent_current IS "Current stock_live grouped to Parent SKU. Stock is visibility-only until reliability gates are enabled.";

-- -----------------------------------------------------------------------------
-- FUNCTION: public.refresh_po_analytics
CREATE OR REPLACE FUNCTION public.refresh_po_analytics()
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO 'public', 'pg_temp'
AS $function$
declare
  v_ref_date date;
  v_sku_rows bigint;
  v_supplier_rows bigint;
begin
  select coalesce(
    max(coalesce(sent_at::date, created_at::date)),
    current_date
  ) into v_ref_date
  from po_headers;

  delete from po_sku_analytics;

  insert into po_sku_analytics(
    parent_sku,as_of_date,po_count_12m,open_po_qty,in_transit_qty,pending_not_shipped_qty,
    received_qty_12m,median_first_receipt_lead_days,p90_first_receipt_lead_days,
    median_full_receipt_lead_days,p90_full_receipt_lead_days,lead_sd_days,lead_sample_count,
    fill_rate_pct,otif_pct,partial_delivery_pct,avg_lots_per_po,next_expected_receipt,
    oldest_open_po_days,active_supply_sources,single_source,supply_confidence,updated_at
  )
  with base as (
    select *
    from v_po_line_execution
    where parent_sku is not null
  ),
  po_lots as (
    select
      b.parent_sku,
      b.po_number,
      max(coalesce(b.shipment_count,0)) as lots
    from base b
    group by b.parent_sku,b.po_number
  ),
  lot_avg as (
    select parent_sku,avg(lots)::numeric avg_lots_per_po
    from po_lots
    group by parent_sku
  )
  select
    b.parent_sku,
    v_ref_date,
    count(distinct b.po_number) filter(
      where coalesce(b.sent_at::date,b.created_at::date) > v_ref_date-365
    )::bigint,
    sum(b.open_qty) filter(
      where coalesce(b.po_status,'') not in ('Closed','Cancelled')
    )::numeric,
    sum(b.in_transit_qty) filter(
      where coalesce(b.po_status,'') not in ('Closed','Cancelled')
    )::numeric,
    sum(b.pending_not_shipped_qty) filter(
      where coalesce(b.po_status,'') not in ('Closed','Cancelled')
    )::numeric,
    sum(b.accepted_received_qty) filter(
      where b.last_receipt_date > v_ref_date-365
    )::numeric,
    percentile_cont(0.50) within group(order by b.first_receipt_lead_days::double precision)
      filter(where b.first_receipt_lead_days is not null)::numeric,
    percentile_cont(0.90) within group(order by b.first_receipt_lead_days::double precision)
      filter(where b.first_receipt_lead_days is not null)::numeric,
    percentile_cont(0.50) within group(order by b.full_receipt_lead_days::double precision)
      filter(where b.full_receipt_lead_days is not null)::numeric,
    percentile_cont(0.90) within group(order by b.full_receipt_lead_days::double precision)
      filter(where b.full_receipt_lead_days is not null)::numeric,
    stddev_pop(b.first_receipt_lead_days) filter(where b.first_receipt_lead_days is not null)::numeric,
    count(b.first_receipt_lead_days)::bigint,
    case when sum(b.effective_order_qty) filter(
      where coalesce(b.sent_at::date,b.created_at::date) > v_ref_date-365
    ) > 0 then
      100*sum(least(b.accepted_received_qty,b.effective_order_qty)) filter(
        where coalesce(b.sent_at::date,b.created_at::date) > v_ref_date-365
      ) / nullif(sum(b.effective_order_qty) filter(
        where coalesce(b.sent_at::date,b.created_at::date) > v_ref_date-365
      ),0)
    end::numeric,
    100*avg((b.otif_flag::int)::numeric) filter(where b.otif_flag is not null),
    100*avg((b.partial_delivery_flag::int)::numeric) filter(
      where b.first_shipped_date is not null or b.first_receipt_date is not null
    ),
    la.avg_lots_per_po,
    min(b.next_expected_delivery) filter(
      where b.open_qty>0 and coalesce(b.po_status,'') not in ('Closed','Cancelled')
    ),
    max(v_ref_date-coalesce(b.sent_at::date,b.created_at::date)) filter(
      where b.open_qty>0
        and coalesce(b.po_status,'') not in ('Closed','Cancelled')
        and coalesce(b.sent_at::date,b.created_at::date) is not null
    )::int,
    count(distinct b.supplier_key) filter(
      where coalesce(b.sent_at::date,b.created_at::date) > v_ref_date-365
        and b.supplier_key is not null
    )::int,
    (count(distinct b.supplier_key) filter(
      where coalesce(b.sent_at::date,b.created_at::date) > v_ref_date-365
        and b.supplier_key is not null
    ) = 1),
    case
      when count(b.first_receipt_lead_days)>=20 then 'HIGH'
      when count(b.first_receipt_lead_days)>=5 then 'MEDIUM'
      when count(b.first_receipt_lead_days)>=1 then 'LOW'
      else 'NONE'
    end,
    now()
  from base b
  left join lot_avg la using(parent_sku)
  group by b.parent_sku,la.avg_lots_per_po;

  get diagnostics v_sku_rows = row_count;

  -- Supplier-level PO execution metrics are merged into the commercial table.
  with s as (
    select
      parent_sku,
      supplier_key,
      max(supplier_name) as supplier_name,
      count(distinct po_number) filter(
        where coalesce(sent_at::date,created_at::date)>v_ref_date-365
      )::bigint as po_count_12m,
      avg(first_receipt_lead_days) filter(where first_receipt_lead_days is not null)::numeric as avg_lead_days,
      percentile_cont(0.50) within group(order by first_receipt_lead_days::double precision)
        filter(where first_receipt_lead_days is not null)::numeric as median_lead_days,
      percentile_cont(0.75) within group(order by first_receipt_lead_days::double precision)
        filter(where first_receipt_lead_days is not null)::numeric as p75_lead_days,
      percentile_cont(0.90) within group(order by first_receipt_lead_days::double precision)
        filter(where first_receipt_lead_days is not null)::numeric as p90_lead_days,
      stddev_pop(first_receipt_lead_days) filter(where first_receipt_lead_days is not null)::numeric as lead_sd_days,
      count(first_receipt_lead_days)::bigint as lead_sample_count,
      case when sum(effective_order_qty) filter(
        where coalesce(sent_at::date,created_at::date)>v_ref_date-365
      )>0 then
        100*sum(least(accepted_received_qty,effective_order_qty)) filter(
          where coalesce(sent_at::date,created_at::date)>v_ref_date-365
        )/nullif(sum(effective_order_qty) filter(
          where coalesce(sent_at::date,created_at::date)>v_ref_date-365
        ),0)
      end::numeric as fill_rate_pct,
      100*avg((otif_flag::int)::numeric) filter(where otif_flag is not null) as otif_pct,
      100*avg((partial_delivery_flag::int)::numeric) filter(
        where first_shipped_date is not null or first_receipt_date is not null
      ) as partial_delivery_pct,
      case when sum(ordered_qty) filter(
        where coalesce(sent_at::date,created_at::date)>v_ref_date-365
      )>0 then
        100*sum(cancelled_qty) filter(
          where coalesce(sent_at::date,created_at::date)>v_ref_date-365
        )/nullif(sum(ordered_qty) filter(
          where coalesce(sent_at::date,created_at::date)>v_ref_date-365
        ),0)
      end::numeric as cancellation_pct,
      avg(coalesce(shipment_count,0))::numeric as avg_lots_per_po,
      sum(open_qty) filter(where coalesce(po_status,'') not in ('Closed','Cancelled'))::numeric as open_po_qty,
      sum(in_transit_qty) filter(where coalesce(po_status,'') not in ('Closed','Cancelled'))::numeric as in_transit_qty,
      sum(pending_not_shipped_qty) filter(where coalesce(po_status,'') not in ('Closed','Cancelled'))::numeric as pending_not_shipped_qty,
      min(next_expected_delivery) filter(
        where open_qty>0 and coalesce(po_status,'') not in ('Closed','Cancelled')
      ) as next_expected_receipt,
      max(v_ref_date-coalesce(sent_at::date,created_at::date)) filter(
        where open_qty>0
          and coalesce(po_status,'') not in ('Closed','Cancelled')
          and coalesce(sent_at::date,created_at::date) is not null
      )::int as oldest_open_po_days,
      case
        when count(first_receipt_lead_days)>=20 then 'HIGH'
        when count(first_receipt_lead_days)>=5 then 'MEDIUM'
        when count(first_receipt_lead_days)>=1 then 'LOW'
        else 'NONE'
      end as supply_confidence
    from v_po_line_execution
    where parent_sku is not null and supplier_key is not null
    group by parent_sku,supplier_key
  )
  insert into purchase_sku_supplier_analytics(
    parent_sku,supplier_key,supplier_name,as_of_date,
    po_count_12m,avg_lead_days,median_lead_days,p75_lead_days,p90_lead_days,
    lead_sd_days,lead_sample_count,fill_rate_pct,otif_pct,partial_delivery_pct,cancellation_pct,
    avg_lots_per_po,open_po_qty,in_transit_qty,pending_not_shipped_qty,next_expected_receipt,
    oldest_open_po_days,supply_confidence,updated_at
  )
  select
    parent_sku,supplier_key,supplier_name,v_ref_date,
    po_count_12m,avg_lead_days,median_lead_days,p75_lead_days,p90_lead_days,
    lead_sd_days,lead_sample_count,fill_rate_pct,otif_pct,partial_delivery_pct,cancellation_pct,
    avg_lots_per_po,coalesce(open_po_qty,0),coalesce(in_transit_qty,0),
    coalesce(pending_not_shipped_qty,0),next_expected_receipt,oldest_open_po_days,
    supply_confidence,now()
  from s
  on conflict(parent_sku,supplier_key) do update set
    supplier_name=coalesce(excluded.supplier_name,purchase_sku_supplier_analytics.supplier_name),
    po_count_12m=excluded.po_count_12m,
    avg_lead_days=excluded.avg_lead_days,
    median_lead_days=excluded.median_lead_days,
    p75_lead_days=excluded.p75_lead_days,
    p90_lead_days=excluded.p90_lead_days,
    lead_sd_days=excluded.lead_sd_days,
    lead_sample_count=excluded.lead_sample_count,
    fill_rate_pct=excluded.fill_rate_pct,
    otif_pct=excluded.otif_pct,
    partial_delivery_pct=excluded.partial_delivery_pct,
    cancellation_pct=excluded.cancellation_pct,
    avg_lots_per_po=excluded.avg_lots_per_po,
    open_po_qty=excluded.open_po_qty,
    in_transit_qty=excluded.in_transit_qty,
    pending_not_shipped_qty=excluded.pending_not_shipped_qty,
    next_expected_receipt=excluded.next_expected_receipt,
    oldest_open_po_days=excluded.oldest_open_po_days,
    supply_confidence=excluded.supply_confidence,
    updated_at=now();

  get diagnostics v_supplier_rows = row_count;

  update purchase_sku_analytics p
  set
    po_count_12m=po.po_count_12m,
    median_lead_days=po.median_first_receipt_lead_days,
    p90_lead_days=po.p90_first_receipt_lead_days,
    lead_sd_days=po.lead_sd_days,
    lead_sample_count=po.lead_sample_count,
    fill_rate_pct=po.fill_rate_pct,
    otif_pct=po.otif_pct,
    partial_delivery_pct=po.partial_delivery_pct,
    avg_lots_per_po=po.avg_lots_per_po,
    open_po_qty=coalesce(po.open_po_qty,0),
    in_transit_qty=coalesce(po.in_transit_qty,0),
    pending_not_shipped_qty=coalesce(po.pending_not_shipped_qty,0),
    next_expected_receipt=po.next_expected_receipt,
    oldest_open_po_days=po.oldest_open_po_days,
    effective_moq=coalesce(pp.default_moq,p.inferred_moq),
    effective_pack_multiple=coalesce(pp.default_pack_multiple,p.inferred_pack_multiple),
    supply_confidence=po.supply_confidence,
    supply_risk_class=coalesce(
      pp.supply_risk_override,
      case
        when coalesce(pp.single_source_override,po.single_source,p.single_source)=true
          and coalesce(po.p90_first_receipt_lead_days,0)>=30 then 'CRITICAL'
        when coalesce(pp.single_source_override,po.single_source,p.single_source)=true then 'HIGH'
        when coalesce(po.otif_pct,100)<70 or coalesce(po.fill_rate_pct,100)<80 then 'HIGH'
        when coalesce(po.otif_pct,100)<85 or coalesce(po.fill_rate_pct,100)<90 then 'MEDIUM'
        else 'LOW'
      end
    ),
    updated_at=now()
  from po_sku_analytics po
  left join purchase_sku_policy pp on pp.parent_sku=po.parent_sku
  where p.parent_sku=po.parent_sku;

  insert into analytics_refresh_log(
    dataset,started_at,finished_at,source_max_date,rows_written,status,details
  )
  values(
    'po_analytics',now(),now(),v_ref_date,v_sku_rows,'SUCCESS',
    jsonb_build_object('supplier_rows_touched',v_supplier_rows)
  );

  return jsonb_build_object(
    'ok',true,
    'as_of_date',v_ref_date,
    'po_sku_rows',v_sku_rows,
    'supplier_rows_touched',v_supplier_rows
  );
exception when others then
  insert into analytics_refresh_log(
    dataset,started_at,finished_at,source_max_date,rows_written,status,error_text,details
  )
  values(
    'po_analytics',now(),now(),v_ref_date,0,'FAILED',sqlerrm,'{}'::jsonb
  );
  raise;
end;
$function$


COMMIT;
