            sum(COALESCE(prl.rejected_qty, 0::numeric)) AS rejected_qty,
            sum(COALESCE(prl.returned_qty, 0::numeric)) AS returned_qty,
            min(pr.received_date) AS first_receipt_date,
            max(pr.received_date) AS last_receipt_date,
            count(DISTINCT pr.receipt_id) AS receipt_count
           FROM po_lines pl_1
             LEFT JOIN po_receipt_lines prl ON prl.po_line_key = pl_1.po_line_key
             LEFT JOIN po_receipts pr ON pr.receipt_id = prl.receipt_id
