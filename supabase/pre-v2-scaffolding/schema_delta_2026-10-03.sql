-- VIEW: public.v_inventory_exception_candidates
CREATE OR REPLACE VIEW public.v_inventory_exception_candidates AS
 WITH p AS (
         SELECT max(v_sales_all.sales_date) AS ref_date
           FROM v_sales_all
        ), tx AS (
         SELECT s.item_code_base AS parent_sku,
            s.sales_date,
            s.voucher_no,
            COALESCE(NULLIF(s.customer_party_key, ''::text), s.customer_id_db_id::text, 'ANON'::text) AS customer_key,
            max(s.customer_name_final) AS customer_name,
            sum(GREATEST(COALESCE(s.qty_num, 0::numeric), 0::numeric)) AS qty,
            sum(GREATEST(COALESCE(s.net_amount_num, 0::numeric), 0::numeric)) AS net_value
           FROM v_sales_all s
             CROSS JOIN p
          WHERE s.item_code_base IS NOT NULL AND s.sales_date > (p.ref_date - '1 year'::interval) AND COALESCE(s.qty_num, 0::numeric) > 0::numeric
          GROUP BY s.item_code_base, s.sales_date, s.voucher_no, (COALESCE(NULLIF(s.customer_party_key, ''::text), s.customer_id_db_id::text, 'ANON'::text))
        ), stats AS (
         SELECT tx.parent_sku,
            percentile_cont(0.25::double precision) WITHIN GROUP (ORDER BY (tx.qty::double precision)) AS q1,
            percentile_cont(0.50::double precision) WITHIN GROUP (ORDER BY (tx.qty::double precision)) AS med,
            percentile_cont(0.75::double precision) WITHIN GROUP (ORDER BY (tx.qty::double precision)) AS q3,
            count(*) AS n
           FROM tx
          GROUP BY tx.parent_sku
        ), scored AS (
         SELECT t.parent_sku,
            t.sales_date,
            t.voucher_no,
            t.customer_key,
            t.customer_name,
            t.qty,
            t.net_value,
            s.med,
            s.q1,
            s.q3,
            s.q3 - s.q1 AS iqr,
            s.n,
                CASE
                    WHEN s.med > 0::double precision THEN t.qty::double precision / s.med
                    ELSE NULL::double precision
                END AS qty_vs_median
           FROM tx t
             JOIN stats s USING (parent_sku)
        )
 SELECT md5(concat_ws('|'::text, parent_sku, sales_date::text, COALESCE(voucher_no, ''::text), customer_key, qty::text)) AS transaction_key,
    parent_sku,
    sales_date,
    voucher_no,
    customer_key,
    customer_name,
    qty,
    net_value,
    med,
    q1,
    q3,
    iqr,
    n AS sample_count,
        CASE
            WHEN n >= 8 AND qty::double precision > (q3 + 3::double precision * iqr) AND COALESCE(qty_vs_median, 0::double precision) >= 5::double precision THEN 'IQR-extreme'::text
            WHEN n >= 8 AND qty::double precision > (q3 + 1.5::double precision * iqr) AND COALESCE(qty_vs_median, 0::double precision) >= 5::double precision THEN 'IQR+median'::text
            WHEN n >= 8 AND COALESCE(qty_vs_median, 0::double precision) >= 10::double precision THEN '10x-median'::text
            ELSE NULL::text
        END AS detection_method,
    qty_vs_median,
        CASE
            WHEN n >= 8 AND qty::double precision > (q3 + 3::double precision * iqr) AND COALESCE(qty_vs_median, 0::double precision) >= 10::double precision THEN 'High'::text
            WHEN n >= 8 AND (qty::double precision > (q3 + 1.5::double precision * iqr) OR COALESCE(qty_vs_median, 0::double precision) >= 10::double precision) THEN 'Medium'::text
            ELSE 'Low'::text
        END AS review_priority
   FROM scored
  WHERE n >= 8 AND (qty::double precision > (q3 + 1.5::double precision * iqr) AND COALESCE(qty_vs_median, 0::double precision) >= 5::double precision OR COALESCE(qty_vs_median, 0::double precision) >= 10::double precision);
;
COMMENT ON VIEW public.v_inventory_exception_candidates IS "Statistical candidates only. They do not alter normalized demand until reviewed in inventory_demand_exception_review.";

