            WHEN r.last_receipt_date IS NOT NULL AND COALESCE(ph.revised_promised_date, ph.promised_date) IS NOT NULL THEN false
            ELSE NULL::boolean
        END AS otif_flag,
    COALESCE(s.shipment_count, 0::bigint) > 1 OR COALESCE(r.receipt_count, 0::bigint) > 1 AS partial_delivery_flag
   FROM po_lines pl
     JOIN po_headers ph ON ph.po_number = pl.po_number
     LEFT JOIN shipped s ON s.po_line_key = pl.po_line_key
     LEFT JOIN received r ON r.po_line_key = pl.po_line_key;
