    ph.created_at,
    ph.approved_at,
    ph.sent_at,
    ph.promised_date,
    ph.revised_promised_date,
    ph.closed_at,
    ph.cancelled_at,
    pl.ordered_qty,
    pl.cancelled_qty,
    GREATEST(pl.ordered_qty - COALESCE(pl.cancelled_qty, 0::numeric), 0::numeric) AS effective_order_qty,
    COALESCE(s.qty_shipped, 0::numeric) AS qty_shipped,
    COALESCE(r.accepted_qty, 0::numeric) AS accepted_received_qty,
    COALESCE(r.rejected_qty, 0::numeric) AS rejected_qty,
    COALESCE(r.returned_qty, 0::numeric) AS returned_qty,
    GREATEST(GREATEST(pl.ordered_qty - COALESCE(pl.cancelled_qty, 0::numeric), 0::numeric) - COALESCE(s.qty_shipped, 0::numeric), 0::numeric) AS pending_not_shipped_qty,
    GREATEST(COALESCE(s.qty_shipped, 0::numeric) - COALESCE(r.accepted_qty, 0::numeric), 0::numeric) AS in_transit_qty,
    GREATEST(GREATEST(pl.ordered_qty - COALESCE(pl.cancelled_qty, 0::numeric), 0::numeric) - COALESCE(r.accepted_qty, 0::numeric), 0::numeric) AS open_qty,
    s.first_shipped_date,
